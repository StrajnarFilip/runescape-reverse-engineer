"""Generate C constants from the existing, version-pinned JSON profile."""
import hashlib
import json
from pathlib import Path
import sys

root=Path(__file__).resolve().parent
source=root.parent/'rs3_reader'/'profile_951_3.json'
data=source.read_bytes();p=json.loads(data)
out=Path(sys.argv[1]) if len(sys.argv)>1 else root/'src'/'profile_generated.h'
def num(x):return int(x,0) if isinstance(x,str) else x
lines=['/* Generated by generate_profile.py; do not edit. */','#ifndef RS3_PROFILE_GENERATED_H',
       '#define RS3_PROFILE_GENERATED_H', '#define P_VERSION '+json.dumps(p['version']),
       '#define P_SHA256 '+json.dumps(p['sha256']), '#define P_PROFILE_SHA256 '+json.dumps(hashlib.sha256(data).hexdigest())]
for key in ['registry_rva','registry_root_offset','tree_key_offset','tree_right_offset','tree_left_offset',
            'function_pointer_offset','function_capture_offset','client_vtable_rva','state_pointer_offset',
            'logic_clock_offset','logic_tick_ms','skills_manager_offset','skills_entries_offset','skill_stride','skill_base_level_offset']:
    lines.append('#define P_'+key.upper()+' '+hex(num(p[key]))+'u')
for domain,spec in p['domains'].items():
    for key,value in spec.items():lines.append('#define P_'+domain.upper()+'_'+key.upper()+' '+hex(num(value))+'u')
for key,value in p['npcs'].items():lines.append('#define P_NPC_'+key.upper()+' '+hex(num(value))+'u')
for key,value in p['inventory'].items():lines.append('#define P_INV_'+key.upper()+' '+hex(num(value))+'u')
names=['health_current','health_max','prayer_packed','adrenaline','gcd_start','gcd_end','gcd_duration','gcd_client_start','gcd_client_end','telos_packed']
lines.append('static const uint32_t p_variable_ids[10] = {'+','.join(str(p['variables'][k])+'u' for k in names)+'};')
lines.append('typedef struct { uint32_t rva, length; unsigned char bytes[64]; } profile_signature;')
lines.append('static const profile_signature p_signatures[] = {')
for sig in p['signatures']:
    b=bytes.fromhex(sig['bytes'])
    if len(b)>64:raise ValueError('Signature exceeds fixed bound')
    lines.append('{'+hex(num(sig['rva']))+'u,'+str(len(b))+'u,{'+','.join(hex(x) for x in b)+'}},')
lines+=['};','#endif','']
out.parent.mkdir(parents=True,exist_ok=True)
out.write_text('\n'.join(lines),encoding='ascii',newline='') if sys.version_info >= (3,10) else out.write_bytes('\n'.join(lines).encode('ascii'))
print(out)
