# Keep this order aligned with enum rs3_variable and the Python field names.
PLAYER_VARIABLES = (
    "health_current",
    "health_max",
    "prayer_packed",
    "adrenaline",
    "gcd_start",
    "gcd_end",
    "gcd_duration",
    "gcd_client_start",
    "gcd_client_end",
    "telos_packed",
)

# client_profile fields that each executable pins independently.
PROFILE_ADDRESS_FIELDS = (
    "registry_rva",
    "player_handler_rva",
    "client_handler_rva",
    "client_vtable_rva",
    "npc_manager_vtable_rva",
    "npc_entity_vtable_rva",
)
OPTIONAL_PROFILE_FIELDS = ("npc_animation_vtable_rva", "npc_action_stamp_offset")


def parse_number(value):
    """Return an integer from a JSON number or a "0x"-prefixed string."""
    return int(value, 0) if isinstance(value, str) else int(value)


def lookup(document, path):
    """Return the value at a tuple path inside nested dictionaries."""
    value = document
    for key in path:
        value = value[key]
    return value


def c_string(text):
    """Return a C string literal for ASCII text."""
    return json.dumps(text)


def sha256_hex(data):
    return hashlib.sha256(data).hexdigest()


def define(name, value):
    return f"#define {name} {value}"


def define_number(name, value):
    return define(name, f"{parse_number(value):#x}u")


def validate_profiles(primary, compatibility):
    """Reject profiles whose layouts the generated code cannot represent."""
    for domain in ("player", "client"):
        fields = primary["domains"][domain]
        if parse_number(fields["count_offset"]) != parse_number(fields["table_offset"]) + 8:
            raise ValueError(f"The {domain} variable count must follow the table pointer")
    if compatibility["combat_layout"]["version"] != primary["version"]:
        raise ValueError("The Compatibility Mode combat layout targets another version")


def primary_addresses(primary):
    """Return the client_profile address fields of the primary executable."""
    addresses = {
        "registry_rva": primary["registry_rva"],
        "player_handler_rva": primary["domains"]["player"]["handler_rva"],
        "client_handler_rva": primary["domains"]["client"]["handler_rva"],
        "client_vtable_rva": primary["client_vtable_rva"],
        "npc_manager_vtable_rva": primary["npcs"]["manager_vtable_rva"],
        "npc_entity_vtable_rva": primary["npcs"]["entity_vtable_rva"],
        # Only the original executable has a verified local player actor layout.
        "player_actor_vtable_rva": primary["local_actor"]["vtable_rva"],
    }
    if primary["npcs"].get("animation_layout_verified"):
        addresses["npc_animation_vtable_rva"] = primary["npcs"]["animation_vtable_rva"]
    return addresses


def compatibility_addresses(compatibility):
    """Return the client_profile address fields of the Compatibility Mode executable."""
    layout = compatibility["combat_layout"]
    addresses = {key: layout[key] for key in PROFILE_ADDRESS_FIELDS}
    for key in OPTIONAL_PROFILE_FIELDS:
        if key in layout:
            addresses[key] = layout[key]
    return addresses


def generate_header(primary_bytes, primary, compatibility):
    compatibility_version = compatibility["version"]
    lines = [
        GENERATED_NOTICE,
        "#ifndef RS3_PROFILE_GENERATED_H",
        "#define RS3_PROFILE_GENERATED_H",
        "",
        "/* Identity of the primary 951-3 executable profile. */",
        define("PROFILE_PRIMARY_VERSION", c_string(primary["version"])),
        define("PROFILE_PRIMARY_SHA256", c_string(primary["sha256"])),
        define("PROFILE_PRIMARY_SOURCE_SHA256", c_string(sha256_hex(primary_bytes))),
        "",
        "/* Identity of the Compatibility Mode executable profile. */",
        define("PROFILE_COMPATIBILITY_VERSION", c_string(compatibility_version)),
        define(
            "PROFILE_COMPATIBILITY_SHORT_VERSION",
            c_string(compatibility_version.split("-", 1)[0]),
        ),
        define("PROFILE_COMPATIBILITY_SHA256", c_string(compatibility["sha256"])),
        "",
        "/* Structure layout shared by both executables. */",
    ]
    lines.extend(define_number(name, lookup(primary, path)) for name, path in LAYOUT_CONSTANTS)
    lines.extend(("", "/* Player tile layout of the Compatibility Mode executable. */"))
    position = compatibility["player_position"]
    lines.extend(define_number(POSITION_CONSTANTS[key], value) for key, value in position.items())
    lines.extend(("", "#endif /* RS3_PROFILE_GENERATED_H */", ""))
    return "\n".join(lines)


def signature_table(name, profile):
    lines = [f"static const profile_signature {name}[] = {{"]
    for signature in profile["signatures"]:
        pattern = bytes.fromhex(signature["bytes"])
        if not 1 <= len(pattern) <= 64:
            raise ValueError("Signatures must contain 1..64 bytes")
        encoded = ", ".join(f"{byte:#04x}" for byte in pattern)
        rva = parse_number(signature["rva"])
        lines.append(f"    {{{rva:#x}u, {len(pattern)}u, {{{encoded}}}}},")
    lines.append("};")
    return lines


def profile_table(name, prefix, signatures, addresses, has_position):
    short_version = f"{prefix}_SHORT_VERSION" if has_position else f"{prefix}_VERSION"
    lines = [
        f"const client_profile {name} = {{",
        f"    .sha256 = {prefix}_SHA256,",
        f"    .version = {prefix}_VERSION,",
        f"    .short_version = {short_version},",
        f"    .signatures = {signatures},",
        f"    .signature_count = sizeof {signatures} / sizeof {signatures}[0],",
    ]
    lines.extend(f"    .{key} = {parse_number(value):#x}u," for key, value in addresses.items())
    lines.extend((f"    .has_position = {int(has_position)},", "};"))
    return lines


def generate_source(primary, compatibility):
    variable_ids = ", ".join(f"{primary['variables'][name]}u" for name in PLAYER_VARIABLES)
    lines = [GENERATED_NOTICE, '#include "profile.h"', ""]
    lines.extend(signature_table("primary_signatures", primary))
    lines.append("")
    lines.extend(signature_table("compatibility_signatures", compatibility))
    lines.extend(
        ("", f"const uint32_t profile_variable_ids[RS3_VARIABLE_COUNT] = {{{variable_ids}}};", "")
    )
    lines.extend(
        profile_table(
            "profile_primary",
            "PROFILE_PRIMARY",
            "primary_signatures",
            primary_addresses(primary),
            has_position=False,
        )
    )
    lines.append("")
    lines.extend(
        profile_table(
            "profile_compatibility",
            "PROFILE_COMPATIBILITY",
            "compatibility_signatures",
            compatibility_addresses(compatibility),
            has_position=True,
        )
    )
    lines.append("")
    return "\n".join(lines)


def generate(primary_bytes, compatibility_bytes):
    """Return (header text, source text) for the two profile documents."""
    primary = json.loads(primary_bytes)
    compatibility = json.loads(compatibility_bytes)
    validate_profiles(primary, compatibility)
    header = generate_header(primary_bytes, primary, compatibility)
    source = generate_source(primary, compatibility)
    return header, source


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("primary_profile", type=Path, help="profiles/profile_951_3.json")
    parser.add_argument("compatibility_profile", type=Path, help="profiles/profile_6ada3f59.json")
    parser.add_argument("output_directory", type=Path, help="Generated-sources directory")
    arguments = parser.parse_args()
    header, source = generate(
        arguments.primary_profile.read_bytes(), arguments.compatibility_profile.read_bytes()
    )
    arguments.output_directory.mkdir(parents=True, exist_ok=True)
    (arguments.output_directory / HEADER_NAME).write_bytes(header.encode("ascii"))
    (arguments.output_directory / SOURCE_NAME).write_bytes(source.encode("ascii"))


if __name__ == "__main__":
    main()
