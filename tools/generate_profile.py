"""Generate a private C header from the version-pinned JSON profiles."""

import argparse
import hashlib
import json
from pathlib import Path

PROFILE_FIELDS = (
    "registry_rva", "registry_root_offset", "tree_key_offset", "tree_right_offset",
    "tree_left_offset", "function_pointer_offset", "function_capture_offset",
    "client_vtable_rva", "state_pointer_offset", "logic_clock_offset", "logic_tick_ms",
    "skills_manager_offset", "skills_entries_offset", "skill_stride",
    "skill_base_level_offset",
)
VARIABLES = (
    "health_current", "health_max", "prayer_packed", "adrenaline", "gcd_start",
    "gcd_end", "gcd_duration", "gcd_client_start", "gcd_client_end", "telos_packed",
)


def number(value):
    return int(value, 0) if isinstance(value, str) else value


def signatures(profile, array):
    lines = [f"static const profile_signature {array}[] = {{"]
    for signature in profile["signatures"]:
        pattern = bytes.fromhex(signature["bytes"])
        if not 1 <= len(pattern) <= 64:
            raise ValueError("Invalid signature length")
        encoded = ", ".join(hex(byte) for byte in pattern)
        lines.append(f"    {{{number(signature['rva']):#x}u, {len(pattern)}u, {{{encoded}}}}},")
    return [*lines, "};"]


def generate(data, position_data):
    profile = json.loads(data)
    position_profile = json.loads(position_data)
    lines = [
        "/* Generated by generate_profile.py; do not edit. */",
        "#ifndef RS3_PROFILE_GENERATED_H",
        "#define RS3_PROFILE_GENERATED_H",
        "#include <stdint.h>",
        "#define P_VERSION " + json.dumps(profile["version"]),
        "#define P_SHA256 " + json.dumps(profile["sha256"]),
        "#define P_PROFILE_SHA256 " + json.dumps(hashlib.sha256(data).hexdigest()),
        "#define POS_VERSION " + json.dumps(position_profile["version"]),
        "#define POS_SHORT_VERSION " + json.dumps(position_profile["version"].split("-", 1)[0]),
        "#define POS_SHA256 " + json.dumps(position_profile["sha256"]),
    ]
    constants = {key: profile[key] for key in PROFILE_FIELDS}
    sections = {**profile["domains"], "npc": profile["npcs"], "inv": profile["inventory"]}
    for section, fields in sections.items():
        constants.update((f"{section}_{key}", value) for key, value in fields.items())
    for key, value in constants.items():
        lines.append(f"#define P_{key.upper()} {number(value):#x}u")
    for key, value in position_profile["player_position"].items():
        lines.append(f"#define POS_{key.upper()} {number(value):#x}u")

    ids = ", ".join(f"{profile['variables'][key]}u" for key in VARIABLES)
    lines.append(f"static const uint32_t p_variable_ids[] = {{{ids}}};")
    lines.append("typedef struct { uint32_t rva, length; unsigned char bytes[64]; } profile_signature;")
    lines.extend(signatures(profile, "p_signatures"))
    lines.extend(signatures(position_profile, "pos_signatures"))
    lines.extend(("#endif", ""))
    return "\n".join(lines).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("profile", type=Path)
    parser.add_argument("position_profile", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    header = generate(args.profile.read_bytes(), args.position_profile.read_bytes())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(header)


if __name__ == "__main__":
    main()
