import hashlib
import json
from pathlib import Path

HEADER_NAME = "profile_generated.h"
SOURCE_NAME = "profile_generated.c"
GENERATED_NOTICE = "/* Generated by tools/generate_profile.py from profiles/*.json; do not edit. */"

