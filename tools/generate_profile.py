"""Generate the private C profile sources from the version-pinned JSON profiles.

The build writes two files into the generated-sources directory:

* ``profile_generated.h`` defines the profile identities and the structure
  layout constants as preprocessor macros.
* ``profile_generated.c`` defines the two ``client_profile`` tables, their
  code signatures and the player variable IDs.

Usage::

    python tools/generate_profile.py PRIMARY_PROFILE COMPATIBILITY_PROFILE OUTPUT_DIRECTORY
"""

